const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),ts=require('typescript');
const ctx={exports:{},Map,Set};vm.createContext(ctx);
vm.runInContext(ts.transpileModule(fs.readFileSync('src/components/onboarding/artistFrontier.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,ctx);
const expand=ctx.exports.expandArtistFrontier;
const a=(id,name=id)=>({id,name,picture_url:''});
const seed=a('prince'), mad=a('madkid'), king=a('king'), cup=a('cupsize');
const initial=[a('other')];
let pool=expand(initial,seed,[mad,king],[seed]);
assert.deepEqual(Array.from(pool,x=>x.id),['prince','madkid','king','other']);
pool=expand(pool,king,[cup,mad,a('new')],[seed,king]);
assert.deepEqual(Array.from(pool,x=>x.id),['prince','madkid','king','cupsize','new','other']);
pool=expand(pool,cup,[a('next'),king],[seed,king,cup]);
assert.deepEqual(Array.from(pool,x=>x.id).slice(0,6),['prince','madkid','king','cupsize','next','new']);
assert.equal(initial.length,1,'Do not mutate existing discovery state');
assert.deepEqual(Array.from(expand([mad],king,[cup],[seed,king]),x=>x.id),['king','cupsize','madkid','prince'],'Do not evict suggestions when there is room for selected nodes');
assert.equal(expand([a('one','Тёмный принц')],a('seed'),[a('alias','темный принц')],[]).length,2,'Do not duplicate aliases');
const huge=Array.from({length:180},(_,i)=>a(String(i)));
const bounded=expand(huge,huge[0],Array.from({length:18},(_,i)=>a('fresh'+i)),[huge[119]]);
assert.equal(bounded.length,120);assert(bounded.some(x=>x.id==='119'),'Retain selected seed at cap');
console.log('Artist frontier passed: Prince → King → CUPSIZE chains, near-seed insertions, alias dedup, stable selection and bounded memory.');
